def source_text(cell: dict) -> str:
    source = cell.get("source", "")
    return "".join(source) if isinstance(source, list) else source


def h2_titles(cells: list[dict]) -> list[str]:
    titles: list[str] = []
    for cell in cells:
        if cell.get("cell_type") != "markdown":
            continue
        for line in source_text(cell).splitlines():
            match = re.match(r"^## (?!#)(.+?)\s*$", line)
            if match:
                titles.append(match.group(1))
    return titles


def original_signature(cell: dict) -> str:
    return json.dumps(cell, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def generated_markdown(cell_id: str, kind: str, anchor: str, source: str) -> dict:
    return {
        "cell_type": "markdown",
        "id": cell_id,
        "metadata": {
            GENERATED_KEY: {
                "kind": kind,
                "anchor": anchor,
            }
        },
        "source": source.rstrip() + "\n",
    }


def task_markdown(parts: tuple[str, str, str, str, str]) -> str:
    prior, question, prediction, hint, boundary = parts
    return f"""> **本节任务卡**
>
> - **前置连接**：{prior}
> - **核心问题**：{question}
> - **运行前预测**：{prediction}
> - **Python/数学提示**：{hint}
> - **解释边界**：{boundary}
"""


def transform(filename: str) -> tuple[int, int]:
    path = ROOT / filename
    notebook = json.loads(path.read_text(encoding="utf-8"))

    # Remove only cells created by this script, making reruns idempotent.
    original_cells = [
        cell
        for cell in notebook["cells"]
        if GENERATED_KEY not in cell.get("metadata", {})
    ]
    original_before = [original_signature(cell) for cell in original_cells]
    outline_before = h2_titles(original_cells)
    expected = EXPECTED_H2[filename]
    if outline_before != expected:
        raise AssertionError(
            f"{filename}: H2 outline before transform differs from the frozen outline\n"
            f"expected={expected}\nactual={outline_before}"
        )

    task_specs = TASKS[filename]
    if list(task_specs) != expected:
        raise AssertionError(f"{filename}: task card keys do not exactly match H2 outline")

    read_specs = READ_CARDS[filename]
    read_matches = {anchor: 0 for anchor, _, _ in read_specs}
    new_cells: list[dict] = []
    task_count = 0

    for index, cell in enumerate(original_cells):
        new_cells.append(cell)

        if index == 0:
            new_cells.append(
                generated_markdown(
                    f"org-nav-{filename[:2]}",
                    "chapter_navigation",
                    "chapter-title",
                    NAVIGATION[filename],
                )
            )

        cell_h2 = []
        if cell.get("cell_type") == "markdown":
            for line in source_text(cell).splitlines():
                match = re.match(r"^## (?!#)(.+?)\s*$", line)
                if match:
                    cell_h2.append(match.group(1))
        if len(cell_h2) > 1:
            raise AssertionError(f"{filename}: more than one H2 in original cell {index}")
        if cell_h2:
            title = cell_h2[0]
            task_count += 1
            new_cells.append(
                generated_markdown(
                    f"org-task-{filename[:2]}-{task_count:02d}",
                    "task_card",
                    title,
                    task_markdown(task_specs[title]),
                )
            )

        if cell.get("cell_type") == "code":
            code = source_text(cell)
            for anchor, slug, card in read_specs:
                if anchor in code:
                    read_matches[anchor] += 1
                    new_cells.append(
                        generated_markdown(
                            f"org-read-{filename[:2]}-{slug}",
                            "reading_card",
                            anchor,
                            card,
                        )
                    )

    if task_count != len(expected):
        raise AssertionError(
            f"{filename}: inserted {task_count} task cards for {len(expected)} H2 sections"
        )
    unmatched = {key: count for key, count in read_matches.items() if count != 1}
    if unmatched:
        raise AssertionError(f"{filename}: read-card anchors must match once: {unmatched}")

    # Prove original cells are untouched and remain in the same order.
    original_after = [
        original_signature(cell)
        for cell in new_cells
        if GENERATED_KEY not in cell.get("metadata", {})
    ]
    if original_after != original_before:
        raise AssertionError(f"{filename}: an original cell changed or moved")

    outline_after = h2_titles(new_cells)
    if outline_after != outline_before:
        raise AssertionError(
            f"{filename}: H2 outline changed during transform\n"
            f"before={outline_before}\nafter={outline_after}"
        )

    notebook["cells"] = new_cells
    path.write_text(
        json.dumps(notebook, ensure_ascii=False, indent=1) + "\n",
        encoding="utf-8",
    )
    return task_count, len(read_specs)


